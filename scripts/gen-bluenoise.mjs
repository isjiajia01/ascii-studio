// Usage: node scripts/gen-bluenoise.mjs src/engine/bluenoise.ts [sigma=1.2] [preview.pgm]
// sigma 1.2 chosen by A/B: 1.5 gave maze-like mid-greys; 1.0 starts to show a Bayer-like lattice.
// Void-and-cluster blue noise (Ulichney 1993), 64x64, own implementation, seeded.
import fs from 'node:fs';
const N=64, T=N*N, SIG=parseFloat(process.argv[3]||'1.2'), R=Math.ceil(SIG*3)+1;
let s=12345; const rnd=()=>{s=(s*1664525+1013904223)>>>0; return s/4294967296;};
const K=[]; for(let dy=-R;dy<=R;dy++)for(let dx=-R;dx<=R;dx++)K.push([dx,dy,Math.exp(-(dx*dx+dy*dy)/(2*SIG*SIG))]);
const E=new Float64Array(T), B=new Uint8Array(T);
const splat=(i,sign)=>{const x=i%N,y=(i/N)|0;for(const[dx,dy,w]of K){E[((y+dy+N)%N)*N+((x+dx+N)%N)]+=sign*w;}};
const add=i=>{B[i]=1;splat(i,1)}, rem=i=>{B[i]=0;splat(i,-1)};
const tight=()=>{let b=-1,bi=0;for(let i=0;i<T;i++)if(B[i]&&E[i]>b){b=E[i];bi=i}return bi};
const void_=()=>{let b=1e18,bi=0;for(let i=0;i<T;i++)if(!B[i]&&E[i]<b){b=E[i];bi=i}return bi};
const init=Math.floor(T*0.1); let c=0; while(c<init){const i=(rnd()*T)|0; if(!B[i]){add(i);c++}}
for(let it=0;it<5000;it++){const t=tight();rem(t);const v=void_();add(v);if(v===t)break;}
const rank=new Int32Array(T); const proto=B.slice();
for(let r=init-1;r>=0;r--){const t=tight();rem(t);rank[t]=r;}
B.set(proto);E.fill(0);for(let i=0;i<T;i++)if(B[i])splat(i,1);
for(let r=init;r<T;r++){const v=void_();add(v);rank[v]=r;}
const seen=new Set(rank); if(seen.size!==T) throw new Error('not a permutation');
const bytes=new Uint8Array(T); for(let i=0;i<T;i++)bytes[i]=Math.min(255,Math.floor((rank[i]+.5)/T*256));
const b64=Buffer.from(bytes).toString('base64');
const out=process.argv[2];
fs.writeFileSync(out,`// 64x64 void-and-cluster blue-noise threshold tile, sigma ${SIG} (generated by scripts/gen-bluenoise.mjs, Ulichney 1993; no third-party data).\nexport const BLUE_N = ${N};\nexport const BLUE_B64 = '${b64}';\nexport function blueNoise(): Uint8Array { const s = atob(BLUE_B64); const a = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) a[i] = s.charCodeAt(i); return a; }\n`);
// preview png-ish pgm
if(process.argv[4]) fs.writeFileSync(process.argv[4],Buffer.concat([Buffer.from(`P5 ${N} ${N} 255\n`),Buffer.from(bytes)]));
console.log('ok',b64.length);
